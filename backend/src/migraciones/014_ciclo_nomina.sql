-- Ciclo de vida del rol de pagos y auditoría.
--   calculado -> validado -> aprobado -> publicado -> pagado
-- Un rol publicado o pagado es inmutable: ni se recalcula, ni se elimina, ni se edita (la API lo
-- rechaza y los disparadores de abajo lo impiden también en la base). Los roles que ya existían quedan
-- en «calculado»: siguen siendo editables hasta que alguien los valide, apruebe y publique.
-- `audit_logs` es solo de inserción: guarda quién hizo qué y cuándo, y no se modifica ni se borra.

ALTER TABLE roles_cabecera
    ADD COLUMN estado      TEXT NOT NULL DEFAULT 'calculado'
        CHECK (estado IN ('calculado', 'validado', 'aprobado', 'publicado', 'pagado')),
    ADD COLUMN validado_en  TEXT,
    ADD COLUMN aprobado_en  TEXT,
    ADD COLUMN publicado_en TEXT,
    ADD COLUMN pagado_en    TEXT;

CREATE TABLE audit_logs (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id     INTEGER NOT NULL REFERENCES cuentas(id),
    -- Sin clave foránea: el registro no cambia aunque el usuario se elimine. NULL = el sistema (seed).
    usuario_id    INTEGER,
    usuario_email TEXT,
    accion        TEXT    NOT NULL,
    entidad       TEXT    NOT NULL,
    entidad_id    INTEGER NOT NULL,
    detalle       TEXT,
    creado_en     TEXT    NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS')
);
CREATE INDEX audit_logs_entidad ON audit_logs (cuenta_id, entidad, entidad_id);

CREATE FUNCTION audit_logs_solo_insertar() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'El registro de auditoría no se modifica ni se borra.';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER audit_logs_inmutable
    BEFORE UPDATE OR DELETE ON audit_logs
    FOR EACH ROW EXECUTE FUNCTION audit_logs_solo_insertar();

-- Un rol publicado solo admite un cambio: pasar a «pagado» (con su fecha).
CREATE FUNCTION proteger_rol_publicado() RETURNS trigger AS $$
BEGIN
    IF OLD.estado IN ('publicado', 'pagado') AND (
        NOT (OLD.estado = 'publicado' AND NEW.estado = 'pagado')
        OR (to_jsonb(NEW) - 'estado' - 'pagado_en') IS DISTINCT FROM (to_jsonb(OLD) - 'estado' - 'pagado_en')
    ) THEN
        RAISE EXCEPTION 'El rol % está %: no se puede modificar.', OLD.id, OLD.estado;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER roles_cabecera_publicado
    BEFORE UPDATE ON roles_cabecera
    FOR EACH ROW EXECUTE FUNCTION proteger_rol_publicado();

CREATE FUNCTION proteger_detalle_publicado() RETURNS trigger AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM roles_cabecera WHERE id = OLD.rol_id AND estado IN ('publicado', 'pagado')) THEN
        RAISE EXCEPTION 'El rol % está publicado: su detalle no se puede modificar.', OLD.rol_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER roles_detalle_publicado
    BEFORE UPDATE ON roles_detalle
    FOR EACH ROW EXECUTE FUNCTION proteger_detalle_publicado();
