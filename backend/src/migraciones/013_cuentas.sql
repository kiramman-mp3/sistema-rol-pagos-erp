-- Cuentas: cada empresa registra su cuenta y todos sus datos son de ella.
--   cuentas   la empresa (nombre y RUC).
--   usuarios  quienes entran a la cuenta (hoy uno por empresa; la tabla deja lugar a más).
-- La cuenta con `plantilla = TRUE` no es de ninguna empresa: guarda las reglas de ley de partida
-- (regímenes, parámetros anuales, escala y orgánico de ejemplo). Cada cuenta nueva recibe una COPIA
-- con copiar_plantilla() y la edita sin afectar a las demás. La página pública usa la plantilla.

CREATE TABLE cuentas (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    TEXT    NOT NULL,
    ruc       TEXT    NOT NULL DEFAULT '',
    plantilla BOOLEAN NOT NULL DEFAULT FALSE,
    creada_en TEXT    NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS')
);
-- Una sola plantilla.
CREATE UNIQUE INDEX cuentas_una_plantilla ON cuentas (plantilla) WHERE plantilla;

CREATE TABLE usuarios (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id  INTEGER NOT NULL REFERENCES cuentas(id) ON DELETE CASCADE,
    email      TEXT    NOT NULL,
    clave_hash TEXT    NOT NULL,
    creado_en  TEXT    NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS')
);
-- El correo identifica al usuario sin importar mayúsculas.
CREATE UNIQUE INDEX usuarios_email ON usuarios (lower(email));

-- La plantilla es la primera cuenta: id 1.
INSERT INTO cuentas (nombre, plantilla) VALUES ('Plantilla del sistema', TRUE);

