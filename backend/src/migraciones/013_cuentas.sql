-- --- copiar_plantilla(destino): las reglas de ley y el orgánico de la plantilla, para otra cuenta -----
-- Los grados se copian con otro id; los puestos y su superior, y la referencia de cada puesto, se
-- reenlazan por su clave natural (régimen y grado; nombre del puesto).
CREATE FUNCTION copiar_plantilla(destino INTEGER) RETURNS VOID AS $$
BEGIN
    INSERT INTO regimenes (cuenta_id, codigo, nombre, descripcion, base_legal, tipo, regimen_servidor,
        regimen_obrero, iess_personal, iess_patronal, recargo_suplementarias, recargo_extraordinarias,
        recargo_descanso, recargo_nocturno, tope_suplementarias_mes, tope_extraordinarias_mes,
        dias_vacaciones, fondos_reserva, meses_para_fondos, aplica_decimo_tercero, aplica_decimo_cuarto,
        aplica_fondos_reserva, aplica_horas_extras, verificado, notas)
    SELECT destino, codigo, nombre, descripcion, base_legal, tipo, regimen_servidor,
        regimen_obrero, iess_personal, iess_patronal, recargo_suplementarias, recargo_extraordinarias,
        recargo_descanso, recargo_nocturno, tope_suplementarias_mes, tope_extraordinarias_mes,
        dias_vacaciones, fondos_reserva, meses_para_fondos, aplica_decimo_tercero, aplica_decimo_cuarto,
        aplica_fondos_reserva, aplica_horas_extras, verificado, notas
    FROM regimenes WHERE cuenta_id = 1;

    INSERT INTO parametros_anuales (cuenta_id, anio, sbu, tabla_ir, fuente)
    SELECT destino, anio, sbu, tabla_ir, fuente FROM parametros_anuales WHERE cuenta_id = 1;

    INSERT INTO escala_salarial (cuenta_id, regimen, grado, denominacion, rmu, rmu_max, es_minimo, fuente)
    SELECT destino, regimen, grado, denominacion, rmu, rmu_max, es_minimo, fuente
    FROM escala_salarial WHERE cuenta_id = 1 ORDER BY id;

    INSERT INTO puestos (cuenta_id, nombre, funcion, responsabilidad, sector, escala_id)
    SELECT destino, p.nombre, p.funcion, p.responsabilidad, p.sector,
           (SELECT n.id FROM escala_salarial n JOIN escala_salarial o ON o.id = p.escala_id
            WHERE n.cuenta_id = destino AND n.regimen = o.regimen AND n.grado = o.grado)
    FROM puestos p WHERE p.cuenta_id = 1 ORDER BY p.id;

    UPDATE puestos n SET superior_id = (
        SELECT sn.id FROM puestos sn JOIN puestos so ON so.nombre = sn.nombre AND so.cuenta_id = 1
        WHERE sn.cuenta_id = destino AND so.id = (SELECT o.superior_id FROM puestos o WHERE o.cuenta_id = 1 AND o.nombre = n.nombre))
    WHERE n.cuenta_id = destino;
END;
$$ LANGUAGE plpgsql;

-- --- Empleados y roles que ya existían: pasan a una cuenta propia, sin usuarios todavía ---------------
-- Si había datos de una empresa se crea la cuenta "Empresa anterior" (cuenta 2) y se queda con ellos:
-- recibe su copia del orgánico y la escala (con la que se reenlazan sus empleados) y sus roles.
-- Con la base vacía no se crea nada: la primera cuenta nace al registrarse una empresa.
DO $$
DECLARE
    legada INTEGER;
BEGIN
    IF EXISTS (SELECT 1 FROM empleados) OR EXISTS (SELECT 1 FROM roles_cabecera) THEN
        INSERT INTO cuentas (nombre, ruc) VALUES ('Empresa anterior', '') RETURNING id INTO legada;
        PERFORM copiar_plantilla(legada);
        UPDATE empleados e SET cuenta_id = legada,
            escala_id = (SELECT n.id FROM escala_salarial n JOIN escala_salarial o ON o.id = e.escala_id
                         WHERE n.cuenta_id = legada AND n.regimen = o.regimen AND n.grado = o.grado),
            puesto_id = (SELECT n.id FROM puestos n JOIN puestos o ON o.id = e.puesto_id
                         WHERE n.cuenta_id = legada AND n.nombre = o.nombre);
        UPDATE roles_cabecera SET cuenta_id = legada;
        -- Los responsables siguen siendo los mismos empleados.
        UPDATE puestos n SET responsable_id = (
            SELECT o.responsable_id FROM puestos o WHERE o.cuenta_id = 1 AND o.nombre = n.nombre)
        WHERE n.cuenta_id = legada;
    END IF;
END $$;
-- El responsable de un puesto es un empleado, y los empleados son de cada cuenta: la plantilla no tiene ninguno.
UPDATE puestos SET responsable_id = NULL WHERE cuenta_id = 1;

