-- Recuperar la contraseña y verificar el correo.
--   usuarios.email_verificado_en   cuándo confirmó que el correo es suyo (NULL = sin confirmar).
--   tokens_usuario                 enlaces de un solo uso que se mandan por correo. Se guarda el hash
--                                  del token, no el token: quien lea la base no puede usarlos.
-- Los usuarios que ya existían quedan sin verificar; verificar no bloquea nada.

ALTER TABLE usuarios ADD COLUMN email_verificado_en TEXT;

CREATE TABLE tokens_usuario (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    tipo       TEXT    NOT NULL CHECK (tipo IN ('recuperar', 'verificar')),
    token_hash TEXT    NOT NULL UNIQUE,
    vence_en   TEXT    NOT NULL,
    usado_en   TEXT,
    creado_en  TEXT    NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS')
);

CREATE INDEX tokens_usuario_por_usuario ON tokens_usuario (usuario_id, tipo);
